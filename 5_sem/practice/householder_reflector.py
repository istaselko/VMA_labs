import numpy as np


def householder_reflection(A, b):
    """
    Приводит систему Ax = b к верхнетреугольному виду Rx = b'
    с помощью метода отражений Хаусхолдера.

    Аргументы:
    A (np.ndarray): Матрица коэффициентов (квадратная).
    b (np.ndarray): Вектор правой части.

    Возвращает:
    (np.ndarray, np.ndarray): Преобразованная матрица R и вектор b'.
    """
    # Создаем копии, чтобы не изменять оригинальные матрицы
    A = A.copy()
    b = b.copy()
    n = len(b)

    # Проходим по всем столбцам, кроме последнего
    # На шаге k мы создаем нули в k-ом столбце ниже диагонали
    for k in range(n - 1):
        # 1. Выбираем вектор для преобразования
        # Это k-й столбец матрицы A, начиная с диагонального элемента A[k,k]
        s = A[k:, k]

        # 2. Вычисляем параметры для матрицы отражения V
        # Длина (норма) вектора s
        norm_s = np.linalg.norm(s)

        # alpha из формулы (3) в тексте. Знак выбирается для численной стабильности,
        # чтобы избежать вычитания близких по значению чисел.
        alpha = -np.copysign(norm_s, s[0])

        # Вектор u = s - alpha*e_1
        # e_1 - это базисный вектор (1, 0, ..., 0)
        u = s.copy()
        u[0] -= alpha

        # Нормализованный вектор v (это и есть w в формуле (2) из текста,
        # только для подматрицы)
        norm_u = np.linalg.norm(u)
        if norm_u == 0:  # Если столбец уже обнулен, пропускаем
            continue
        v = u / norm_u
        v = v.reshape(-1, 1)  # Превращаем в вектор-столбец

        # 3. Применяем преобразование (умножение на V) к оставшейся части матрицы A и вектору b
        # Вместо явного формирования матрицы V = I - 2*v*v^T, мы используем
        # эквивалентную и более быструю операцию: M' = M - 2*v*(v^T @ M)

        # Преобразование подматрицы A[k:, k:]
        sub_matrix_A = A[k:, k:]
        # v.T @ sub_matrix_A - это скалярное произведение v на каждый столбец подматрицы
        # Результат - вектор-строка
        prod_A = v.T @ sub_matrix_A
        # v @ prod_A - это внешнее произведение, которое дает матрицу нужного размера
        A[k:, k:] -= 2 * (v @ prod_A)

        # Преобразование соответствующей части вектора b
        sub_vector_b = b[k:].reshape(-1, 1)
        prod_b = v.T @ sub_vector_b  # Скалярное произведение
        b[k:] -= (2 * v * prod_b).flatten()

    return A, b


def back_substitution(R, b_prime):
    """
    Решает систему Rx = b' с верхнетреугольной матрицей R
    методом обратной подстановки.

    Аргументы:
    R (np.ndarray): Верхнетреугольная матрица.
    b_prime (np.ndarray): Преобразованный вектор правой части.

    Возвращает:
    np.ndarray: Вектор решений x.
    """
    n = len(b_prime)
    x = np.zeros(n)

    # x_n = b'_n / R_nn
    x[n - 1] = b_prime[n - 1] / R[n - 1, n - 1]

    # Идем по строкам снизу вверх, от n-2 до 0
    for i in range(n - 2, -1, -1):
        # Вычисляем сумму R_ij * x_j для j от i+1 до n
        sum_ax = np.dot(R[i, i + 1 :], x[i + 1 :])
        # Находим x_i
        x[i] = (b_prime[i] - sum_ax) / R[i, i]

    return x


def main():
    """Главная функция для взаимодействия с пользователем."""
    print("--- Решение СЛАУ Ax=b методом отражений (Хаусхолдера) ---")

    try:
        n = int(input("Введите порядок матрицы (n): "))
        if n <= 0:
            print("Порядок матрицы должен быть положительным числом.")
            return

        A = np.zeros((n, n))
        b = np.zeros(n)

        print("\nВведите элементы матрицы A (построчно, числа через пробел):")
        for i in range(n):
            while True:
                try:
                    row_str = input(f"Строка {i+1}: ")
                    row = list(map(float, row_str.split()))
                    if len(row) != n:
                        print(f"Ошибка: в строке должно быть {n} элементов.")
                        continue
                    A[i] = row
                    break
                except ValueError:
                    print("Ошибка: вводите только числа, разделенные пробелом.")

        print("\nВведите элементы вектора b (через пробел):")
        while True:
            try:
                b_str = input("Вектор b: ")
                b = np.array(list(map(float, b_str.split())))
                if len(b) != n:
                    print(f"Ошибка: в векторе должно быть {n} элементов.")
                    continue
                break
            except ValueError:
                print("Ошибка: вводите только числа, разделенные пробелом.")

        print("\n--- Исходная система ---")
        print("Матрица A:")
        print(np.round(A, 4))
        print("\nВектор b:")
        print(np.round(b, 4))

        # Шаг 1: Приведение к верхнетреугольному виду
        R, b_prime = householder_reflection(A, b)

        print("\n--- Система после преобразования Хаусхолдера ---")
        print("Верхнетреугольная матрица R:")
        print(np.round(R, 4))
        print("\nПреобразованный вектор b':")
        print(np.round(b_prime, 4))

        # Шаг 2: Решение методом обратной подстановки
        x = back_substitution(R, b_prime)

        print("\n--- Результат ---")
        print("Вектор решений x:")
        print(np.round(x, 4))

        # Проверка решения
        print("\n--- Проверка ---")
        print("A * x =")
        print(np.round(A @ x, 4))
        print("\nИсходный вектор b:")
        print(np.round(b, 4))

        # Проверка на основе нормы разницы
        if np.allclose(A @ x, b):
            print("\nРешение верно!")
        else:
            print("\nРешение неточное (возможно, из-за ошибок округления).")

    except ValueError:
        print("\nОшибка ввода. Пожалуйста, введите корректное число.")
    except Exception as e:
        print(f"\nПроизошла непредвиденная ошибка: {e}")


if __name__ == "__main__":
    main()
